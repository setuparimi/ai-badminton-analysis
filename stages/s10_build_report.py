#!/usr/bin/env python3
"""Stage 10 - REPORT (document).

Builds report.md from the numbers in work/*.json. Every figure is read from those files.
The coaching section is NOT generated by this script: it is written by you or your AI
assistant from report_data.json and saved as coaching.md (rules for writing it are in
CLAUDE.md), then merged here. Without coaching.md the report says so.

Run:
    python stages/s10_build_report.py --work work [--label "my match"] [--coaching work/coaching.md]
"""
import argparse
import json
from pathlib import Path

from common import NO_CHANGE, chain_status, load_config, near_team_at, team_phrase


def mmss(s):
    return f"{int(s // 60)}:{int(s % 60):02d}"


def pct(a, b):
    return f"{100 * a / b:.0f}%" if b else "n/a"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--work", required=True)
    ap.add_argument("--label", default="match video")
    ap.add_argument("--coaching", help="coaching.md (default: <work>/coaching.md)")
    args = ap.parse_args()
    W = Path(args.work)
    L = lambda n: json.loads((W / n).read_text())
    R, PTS, SV, SC = L("report_data.json"), L("points.json")["rallies"], L("serves.json"), L("score.json")
    M, PO, CAL, PL, PK, OV = L("motion.json"), L("pose_stats.json")["stats"], L("calib.json"), L("players.json"), L("pickups.json"), L("overlay.json")
    cfg = load_config(W / "players_config.json")
    mine, theirs = team_phrase(cfg)
    n_all, n_dec = len(PTS), R["n_decided"]
    you, mate = R["pose"]["A_you"]["by_side"].get("near"), R["pose"]["A_partner"]["by_side"].get("near")
    ms, pair, sens = R["motion_summary"]["you"], R["motion_summary"]["pair"], R["sensitivity_confident_chains_only"]
    a_srv, a_rcv = R["A_when_serving"], R["A_when_receiving"]
    sw, sr = R["A_when_serving_you"], R["A_when_serving_partner"]
    sa, sb = R["streak_A"], R["streak_B"]
    q, tot = R["quarters"], R["motion_totals"]
    lost_serves = [(p["rally"], mmss(p["start"])) for p in PTS if p["server_player"] == "A_you" and p["winner"] == "B"]
    won_serves = [(p["rally"], mmss(p["start"])) for p in PTS if p["server_player"] == "A_you" and p["winner"] == "A"]
    chains = chain_status(SV, SC)
    confirmed = [c for c in chains if c["status"] == "confirmed"]
    cue_only = [c for c in chains if c["status"] == "cue only"]
    n_conf = sum(c["n"] for c in confirmed)
    span = lambda cs: ", ".join(f"{c['rallies'][0]}-{c['rallies'][1]}" if c["rallies"][0] != c["rallies"][1] else f"{c['rallies'][0]}" for c in cs) or "none"
    swap = None if PL["tc"] >= NO_CHANGE else mmss(PL["tc"])
    near_you = [p["rally"] for p in PTS[:-1] if near_team_at((p["start"] + p["end"]) / 2, PL["tc"], PL["first_near"]) == "A"]
    last = R["last_scoreboard"]
    ls, lr = last["score"]
    if last["server_team"] == "A":
        finals = f"{ls + 1}-{lr} to your team if it won the last rally, {ls}-{lr + 1} to the opponents if it lost it"
        a_before, b_before = ls, lr
    else:
        finals = f"{lr}-{ls + 1} to the opponents if they won the last rally, {lr + 1}-{ls} to your team if they lost it"
        a_before, b_before = lr, ls
    coach_path = Path(args.coaching) if args.coaching else W / "coaching.md"
    coaching = coach_path.read_text() if coach_path.exists() else (
        "_No coaching text yet. The numbers above are measurements. Ask your AI assistant to write `coaching.md` "
        "from `report_data.json` following the rules in CLAUDE.md, then run this script again._")

    def row(label, key, fmt="{:.2f}"):
        m = ms[key]
        return f"| {label} | {fmt.format(m['won'])} | {fmt.format(m['lost'])} | {m['p']:.2f} |"

    md = f"""# Badminton match analysis: {args.label}

Your team ({mine}) against {theirs}. Doubles, one game.

## What was measured, and how sure it is

* **Score:** your team was {a_before}-{b_before} before the final rally ({'your team' if last['server_team'] == 'A' else 'the opponents'} serving). The winner of that last rally is not shown, so the game finished {finals}. {R['ties']} ties, {R['lead_changes']} lead changes, longest run {max(sa[0], sb[0])} points.
* **Measured directly:** where the four players stood (court metres), rally start and end times, distance, speed and posture. The scoreboard was read from {len(OV['runs'])} on-screen overlays.
* **Inferred:** *which team won each rally*. The scoreboard shows the server's score but not the team, so the serving team is worked out from how the players stand before each serve. It is independently confirmed for {n_conf} of {n_all} rallies (blocks {span(confirmed)}); blocks {span(cue_only)} rest on the position cue alone.
* **Rougher:** far-court positions (see section 6).

![score](images/01_match_summary.png)

## 1. The match

| | |
|---|---|
| Rallies | {n_all} (median {sorted(p['duration'] for p in PTS)[len(PTS) // 2]:.1f} s, longest {max(p['duration'] for p in PTS[:-1]):.1f} s) |
| Your team's points by quarter | {q[0]['A']}/{q[0]['n']}, {q[1]['A']}/{q[1]['n']}, {q[2]['A']}/{q[2]['n']}, {q[3]['A']}/{q[3]['n']} |
| Longest run, your team | {sa[0]} points from rally {sa[1][0]} at {mmss(sa[1][1])} |
| Longest run, opponents | {sb[0]} points from rally {sb[1][0]} at {mmss(sb[1][1])} |
| Teams changed ends | {('at ' + swap) if swap else 'no'} |

Analysis starts at {mmss(PL['start'])}; anything before that (title card, teaser, warm-up) is ignored.

## 2. Serving and receiving

| | won / played | |
|---|---|---|
| Your team when serving | {a_srv[0]} / {a_srv[1]} | {pct(*a_srv)} |
| Your team when receiving | {a_rcv[0]} / {a_rcv[1]} | {pct(*a_rcv)} |
| Points when **you** served | {sw[0]} / {sw[1]} | {pct(*sw)} |
| Points when your partner served | {sr[0]} / {sr[1]} | {pct(*sr)} |

Serving versus receiving: p = {R['serve_vs_receive_p']:.2f}. Rallies you served and lost: {', '.join(f'R{r} {t}' for r, t in lost_serves) or 'none'}; won: {', '.join(f'R{r} {t}' for r, t in won_serves) or 'none'}.

## 3. Rally length

| rally length | rallies | your team won |
|---|---|---|
""" + "\n".join(f"| {b['bucket']} | {b['n']} | {b['A_won']} ({pct(b['A_won'], b['n'])}) |" for b in R["by_length"]) + f"""

## 4. You, won versus lost rallies (movement)

Court metres from the calibrated camera; {ms['distance_m']['n_won']} won and {ms['distance_m']['n_lost']} lost rallies. p is a Mann-Whitney test; with 9 comparisons about one p below 0.05 is expected by chance.

| | won | lost | p |
|---|---|---|---|
{row('distance per rally (m)', 'distance_m', '{:.1f}')}
{row('mean speed (m/s)', 'mean_speed')}
{row('peak speed, 95th percentile (m/s)', 'peak_speed')}
{row('share of time at the net (<= 2.5 m)', 'front')}
{row('share of time mid-court', 'mid')}
{row('share of time at the back (> 4.5 m)', 'back')}
| **your pair** | | | |
| open gap in your half (m) | {pair['open_gap_mean']['won']:.2f} | {pair['open_gap_mean']['lost']:.2f} | {pair['open_gap_mean']['p']:.2f} |
| time within 1.5 m of your partner | {pair['crowded']['won']:.2f} | {pair['crowded']['lost']:.2f} | {pair['crowded']['p']:.3f} |

Over the game: you ran {tot['A_you']['total_distance_m']:.0f} m in {tot['A_you']['rallies_used']} rallies ({tot['A_you']['distance_per_rally']:.1f} m per rally, {tot['A_you']['mean_speed']:.2f} m/s); your partner {tot['A_partner']['total_distance_m']:.0f} m; the opponents {tot['B_opp1']['total_distance_m']:.0f} m and {tot['B_opp2']['total_distance_m']:.0f} m.

Re-running the same comparison on only the rallies whose serving team is best backed up ({sens['rallies']} rallies): time within 1.5 m of your partner {sens['metrics']['crowded']['won']:.2f} vs {sens['metrics']['crowded']['lost']:.2f} (p = {sens['metrics']['crowded']['p']:.3f}); distance {sens['metrics']['distance_m']['won']:.1f} vs {sens['metrics']['distance_m']['lost']:.1f} m (p = {sens['metrics']['distance_m']['p']:.2f}).

![heatmaps](images/05_heatmaps.png)

## 5. Posture
""" + (f"""
Near half only ({len(near_you)} rallies, {you['samples']} frames of you). Body landmarks need a large person, so they exist only while a player is near the camera. Racket hand detected as **{'left' if R['pose']['A_you']['racket_arm'] == 'L' else 'right'}** (check it by eye on a few swings: it rests on a small number of overhead frames).

| | you | your partner |
|---|---|---|
| knee angle, median (180 = straight leg) | {you['knee_median']:.0f} deg | {mate['knee_median']:.0f} deg |
| frames with knees bent under 150 deg | {you['bent_lt150']:.0%} | {mate['bent_lt150']:.0%} |
| racket hand held above the hip | {you['racket_up_share']:.0%} | {mate['racket_up_share']:.0%} |
| won rallies / lost rallies: knees bent | {you['won']['bent_lt150']:.0%} / {you['lost']['bent_lt150']:.0%} | {mate['won']['bent_lt150']:.0%} / {mate['lost']['bent_lt150']:.0%} |
| won rallies / lost rallies: racket hand up | {you['won']['racket_up_share']:.0%} / {you['lost']['racket_up_share']:.0%} | {mate['won']['racket_up_share']:.0%} / {mate['lost']['racket_up_share']:.0%} |
""" if you and mate else "\nNo posture numbers: the posture stage found too few frames of a large, near-side player.\n") + f"""
Pickups (stage 9): {'usable' if PK['usable'] else 'not usable on this video'}: in {PK['rallies_with_single_bending_team']} of {n_all - 1} rallies exactly one team bends near the end of the rally, and that team is the loser {PK['agree_with_loser']} times ({pct(PK['agree_with_loser'], PK['rallies_with_single_bending_team'])}; chance is 50%).

## 6. Limits of these numbers

* **Far-court accuracy.** Pixels per metre from the calibration: {'; '.join(f"{k} {v:.0f}" for k, v in CAL['pixels_per_metre'].items())}. Few pixels per metre means less precise positions, which is why the far half of the court is rougher than the near half.
* **Tracking coverage per player (share of frames with a position):** {', '.join(f"{k} {v:.0%}" for k, v in R['tracking'].items())}.
* **Who won each rally** is inferred. The independent test: while a team keeps winning on serve, the same player must serve. It held in {SC['same_server_checks']['same_player']} of {SC['same_server_checks']['pairs']} pairs, against {SC['same_server_checks']['if_direction_were_wrong']['same_player']} of {SC['same_server_checks']['if_direction_were_wrong']['pairs']} if the inference were backwards.
* **The last rally** is excluded from per-rally statistics: after the final point the players keep moving.
* **Clothing colour** identifies people only inside the court area, from shirt colours in players_config.json.

## 7. Checks that ran

| stage | check | result |
|---|---|---|
| 2 calibrate | court model against hand-picked points | fit error {CAL['rms_px']:.1f} px |
| 3 players | share of frames with a position | {min(R['tracking'].values()):.0%} to {max(R['tracking'].values()):.0%} |
| 4 serves | both diagonal service quadrants occupied | {sum(1 for s in SV['serves'] if s['diag_quadrants_occupied'])} of {len(SV['serves'])} windows |
| 5 score | replay against the scoreboard | {len(SC['problems'])} disagreements |
| 5 score | same player keeps serving | {SC['same_server_checks']['same_player']} of {SC['same_server_checks']['pairs']} |
| 9 pickups | bends point at the losing side | {PK['agree_with_loser']} of {PK['rallies_with_single_bending_team']} |

## Coaching

{coaching}
"""
    (W / "report.md").write_text(md)
    print(f"wrote {W / 'report.md'} ({len(md.splitlines())} lines); coaching section: {'included' if coach_path.exists() else 'placeholder'}")


if __name__ == "__main__":
    main()
